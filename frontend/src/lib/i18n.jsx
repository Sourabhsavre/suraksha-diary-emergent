const I18nContext = createContext({ lang: 'hi', setLang: () => {}, t: (k) => k });

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(() => localStorage.getItem(LANG_KEY) || 'hi');
  useEffect(() => {
    localStorage.setItem(LANG_KEY, lang);
    document.documentElement.lang = lang;
  }, [lang]);
  const setLang = useCallback((l) => setLangState(l === 'en' ? 'en' : 'hi'), []);
  const t = useCallback((key) => (STRINGS[lang] && STRINGS[lang][key]) || STRINGS.hi[key] || key, [lang]);
  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
